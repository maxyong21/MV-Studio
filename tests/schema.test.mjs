import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {database} from './helpers/database.mjs';

test('schema migration, RLS, permissions, rate limits, publication and duplicate protection',async()=>{
  const db=await database();
  try{
    await db.exec(await readFile('supabase/migrations/20261024_growth_and_reliability.sql','utf8'));
    await db.exec((await readFile('supabase/schema.sql','utf8')).replace('create extension if not exists pgcrypto;',''));
    const securityMigration=await readFile('supabase/migrations/20261104_security_hardening.sql','utf8');
    await db.exec(securityMigration);await db.exec(securityMigration);
    await db.query('alter table public.enquiries rename column email_message_id to resend_email_id');
    const smtpMigration=await readFile('supabase/migrations/20261104_gmail_smtp.sql','utf8');
    await db.exec(smtpMigration);await db.exec(smtpMigration);
    assert.ok((await db.query("select 1 from information_schema.columns where table_schema='public' and table_name='enquiries' and column_name='email_message_id'")).rows.length);
    assert.equal((await db.query("select 1 from information_schema.columns where table_schema='public' and table_name='enquiries' and column_name='resend_email_id'")).rows.length,0);
    const workspaceMigration=await readFile('supabase/migrations/20261104_enquiry_workspace.sql','utf8');
    await db.exec(workspaceMigration);await db.exec(workspaceMigration);
    const workspaceColumns=(await db.query("select column_name from information_schema.columns where table_schema='public' and table_name='enquiries'")).rows.map(row=>row.column_name);
    assert.ok(['assigned_to','internal_notes','follow_up_at'].every(name=>workspaceColumns.includes(name)));
    assert.equal((await db.query('select count(*)::int as n from public.services')).rows[0].n,4);
    const publicDetails=await readFile('supabase/migrations/20261027_complete_public_details.sql','utf8');
    assert.ok((await db.query("select challenge,solution,outcome from projects where name='APMoodle'")).rows.every(p=>p.challenge&&p.solution&&p.outcome));
    await db.query("update projects set outcome='Admin verified project outcome' where name='APMoodle'");
    await db.query("update services set scope='Admin approved package scope' where name='Landing Page'");
    await db.exec(publicDetails);await db.exec(publicDetails);
    assert.equal((await db.query("select outcome from projects where name='APMoodle'")).rows[0].outcome,'Admin verified project outcome');
    assert.equal((await db.query("select scope from services where name='Landing Page'")).rows[0].scope,'Admin approved package scope');
    assert.equal((await db.query('select count(*)::int as n from testimonials')).rows[0].n,0);
    const heroMigration=await readFile('supabase/migrations/20261026_clear_hero_slogans.sql','utf8');
    await db.query("update site_content set content=content||jsonb_build_object('hero_title','Digital, made more human.','hero_description','We build thoughtful websites and digital tools that help ambitious small businesses move forward.')");
    await db.exec(heroMigration);
    assert.equal((await db.query("select content->>'hero_title' as title from site_content")).rows[0].title,'Websites and web apps for Malaysian small businesses.');
    await db.query("update site_content set content=content||jsonb_build_object('hero_title','Our custom studio headline','hero_slogan_2','')");
    await db.exec(heroMigration);
    const hero=(await db.query('select content from site_content')).rows[0].content;
    assert.equal(hero.hero_title,'Our custom studio headline');assert.equal(hero.hero_slogan_2,'');
    await db.query("update site_content set content=content||jsonb_build_object('contact_phones',jsonb_build_array('+60 16-223 8196','+60 11-5403 9173'))");
    const whatsappMigration=await readFile('supabase/migrations/20261026_short_enquiry_whatsapp.sql','utf8');
    await db.exec(whatsappMigration);await db.exec(whatsappMigration);
    const contacts=(await db.query('select content from site_content')).rows[0].content;
    assert.equal(contacts.whatsapp_number,'011-5403 9173');assert.deepEqual(contacts.contact_phones,['+60 16-223 8196','+60 11-5403 9173']);
    await assert.rejects(db.query("insert into testimonials(name,quote,active) values ('Client','A real quote with permission.',true)"),e=>e.code==='23514');
    await db.query("insert into testimonials(name,quote,permission_confirmed,active) values ('Client','A real quote with permission.',true,true),('Draft','A private draft without approval.',false,false)");
    await db.exec('set role anon');
    assert.equal((await db.query('select count(*)::int as n from testimonials')).rows[0].n,1);
    await assert.rejects(db.query('select * from enquiries'),e=>e.code==='42501');
    await assert.rejects(db.query("insert into services(name) values ('Unauthorized')"),e=>e.code==='42501');
    await assert.rejects(db.query("select consume_enquiry_rate_limit('public')"),e=>e.code==='42501');
    await db.exec('reset role; set role service_role');
    assert.ok((await db.query('select * from feature_options')).rows.length);
    const results=[];for(let i=0;i<6;i++)results.push((await db.query("select consume_enquiry_rate_limit('test-limit',5,3600) as ok")).rows[0].ok);
    assert.deepEqual(results,[true,true,true,true,true,false]);
    await assert.rejects(db.query("select consume_enquiry_rate_limit('bad-limit',1001,3600)"),e=>e.code==='22023');
    await db.query("insert into enquiries(name,company_name,phone,email,request_id) values ('Client','Company','+60123456789','client@example.test','22222222-2222-4222-8222-222222222222')");
    const workspaceEnquiry=(await db.query("select id from enquiries where email='client@example.test'")).rows[0].id;
    assert.equal((await db.query('select count(*)::int as n from enquiry_status_history where enquiry_id=$1',[workspaceEnquiry])).rows[0].n,1);
    await db.query("insert into enquiry_quotes(enquiry_id,version,scope,items,one_time_total) values($1,1,'Bakery ordering website','[{\"name\":\"Ordering\",\"amount\":500,\"cadence\":\"one-time\"}]',500)",[workspaceEnquiry]);
    assert.equal((await db.query('select version from enquiry_quotes where enquiry_id=$1',[workspaceEnquiry])).rows[0].version,1);
    await db.query("update enquiries set status='contacted',assigned_to='Team',internal_notes='Private follow-up',follow_up_at=now() where id=$1",[workspaceEnquiry]);
    assert.equal((await db.query('select count(*)::int as n from enquiry_status_history where enquiry_id=$1',[workspaceEnquiry])).rows[0].n,2);
    await assert.rejects(db.query("insert into enquiries(name,company_name,phone,email,request_id) values ('Client','Company','+60123456789','client@example.test','22222222-2222-4222-8222-222222222222')"),e=>e.code==='23505');
    await db.exec('reset role');
    const ids=(await db.query('select id from projects')).rows;
    for(const {id} of ids)await db.query('update projects set show_in_footer=true where id=$1',[id]);
    await assert.rejects(db.query("insert into projects(name,show_in_footer) values ('Fifth footer project',true)"),e=>e.code==='23514');
    const adminId='33333333-3333-4333-8333-333333333333';
    await db.query('insert into auth.users(id) values ($1)',[adminId]);await db.query('insert into admin_users(user_id) values ($1)',[adminId]);
    await db.exec('set role authenticated');
    await assert.rejects(db.query("insert into testimonials(name,quote) values ('Stranger','This should not be allowed.')"),e=>e.code==='42501');
    await db.query("select set_config('request.jwt.claim.sub',$1,false)",[adminId]);
    await db.query("insert into testimonials(name,quote) values ('Approved admin','Admin-created draft quote.')");
    assert.equal((await db.query('select count(*)::int as n from testimonials')).rows[0].n,3);
    await db.exec('reset role');
    assert.equal((await db.query("select to_regclass('public.whatsapp_settings') as relation")).rows[0].relation,null,'Fresh installations do not create retired bot tables');
    const shutdown=await readFile('supabase/disable-whatsapp-bot.sql','utf8');await db.exec(shutdown);
    await db.exec(`
      create table public.whatsapp_settings(id integer primary key,enabled boolean,updated_at timestamptz);
      insert into public.whatsapp_settings values(1,true,now());
      create table public.legacy_channel_archive(id integer primary key,message text);
      insert into public.legacy_channel_archive values(1,'Retained customer history');
      create schema cron;
      create table cron.job(jobid bigint primary key,jobname text);
      insert into cron.job values(1,'mv-whatsapp-recovery'),(2,'unrelated-maintenance');
      create function cron.unschedule(bigint) returns boolean language plpgsql as $$
      begin delete from cron.job where jobid=$1; return found; end; $$;
    `);
    await db.exec(shutdown);await db.exec(shutdown);
    assert.equal((await db.query('select enabled from public.whatsapp_settings where id=1')).rows[0].enabled,false);
    assert.deepEqual((await db.query('select jobname from cron.job')).rows.map(row=>row.jobname),['unrelated-maintenance']);
    assert.equal((await db.query('select message from public.legacy_channel_archive')).rows[0].message,'Retained customer history');
  }finally{await db.close();}
});
